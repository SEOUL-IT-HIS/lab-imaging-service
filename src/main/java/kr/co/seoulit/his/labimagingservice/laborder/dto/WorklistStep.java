package kr.co.seoulit.his.labimagingservice.laborder.dto;

/**
 * 워크리스트의 "다음에 해야 할 일".
 *
 * ⚠ DB 에 저장되는 값이 아니다. 접수 하나에 대해 일정·검체·판정 데이터가 어디까지 쌓였는지를 보고
 *   서버가 매번 계산해서 내려주는 화면용 값이다. (그래서 entity 가 아니라 dto 패키지에 있다)
 *
 * ⚠ 이 계산을 프론트에 맡기지 않는 이유 —
 *   "담당자가 바뀌어도 다음에 뭘 해야 할지 목록에서 바로 보인다"가 워크리스트의 목적인데,
 *   판단 규칙이 화면마다 흩어지면 검사 화면과 영상 화면이 서로 다르게 판단하기 시작한다.
 *   규칙은 서버 한 곳에만 둔다. (LabWorklistService.decideNextStep)
 */
public enum WorklistStep {

    /** 일정 등록 대기 — 최종 일정이 없다. */
    SCHEDULE,

    /** 검체 등록 대기 — 일정은 잡혔는데 검체가 하나도 없다. */
    SPECIMEN,

    /** 재채취 대기 — 부적합 판정에서 재채취를 요청했다. 검체를 다시 받아야 한다. */
    RECOLLECT,

    /** 적합성 판정 대기 — 검체는 있는데 아직 판정 안 된 게 남았다. */
    ACCEPTANCE,

    /** 결과 등록 대기 — 판정까지 끝났다. (결과 등록 기능은 아직 미구현) */
    RESULT
}
